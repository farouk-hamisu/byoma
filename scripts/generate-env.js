// Generates /env.js (browser-safe configuration) from .env and/or process.env.
// Only public values are written: SUPABASE_URL, SUPABASE_ANON_KEY, APP_ORIGIN.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function parseEnvFile(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const rawLine of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

const fileEnv = parseEnvFile(resolve(root, '.env'));
const merged = { ...fileEnv };
for (const key of ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'APP_ORIGIN', 'SUPABASE_PROXY_PATH']) {
  if (process.env[key]) merged[key] = process.env[key];
}

const config = {
  SUPABASE_URL: merged.SUPABASE_URL || 'https://YOUR_PROJECT_REF.supabase.co',
  SUPABASE_ANON_KEY: merged.SUPABASE_ANON_KEY || 'YOUR_SUPABASE_ANON_KEY',
  APP_ORIGIN: merged.APP_ORIGIN || 'http://localhost:3000',
  SUPABASE_PROXY_PATH: merged.SUPABASE_PROXY_PATH || '/api/supabase',
};

const banner =
  '// Generated by scripts/generate-env.js — do not commit real values.\n' +
  '// Only public-safe configuration is written here.\n';

writeFileSync(resolve(root, 'env.js'), `${banner}window.__APP_CONFIG__ = ${JSON.stringify(config, null, 2)};\n`);

const missing = [];
if (config.SUPABASE_URL.includes('YOUR_PROJECT_REF')) missing.push('SUPABASE_URL');
if (config.SUPABASE_ANON_KEY.startsWith('YOUR_')) missing.push('SUPABASE_ANON_KEY');

if (missing.length) {
  console.log(`env.js written with placeholders. Fill in: ${missing.join(', ')}`);
} else {
  console.log('env.js written with configured values.');
}
