// Bundles each Supabase Edge Function into ONE self-contained file under
// dist/functions/<name>.js so it can be deployed by pasting into the Supabase
// Dashboard code editor (single-file; cannot see ../_shared imports).
//
// - Relative imports (../_shared/*.js) are inlined into the output.
// - `npm:` specifiers stay external; the edge runtime resolves them natively.
// - Source of truth remains supabase/functions/ — always edit there, then
//   regenerate with: npm run bundle
import { readdirSync, existsSync, mkdirSync, statSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const functionsDir = join(root, 'supabase', 'functions');
const outDir = join(root, 'dist', 'functions');
const ESBUILD_ARGS = ['--yes', 'esbuild@0.25.10'];

const names = readdirSync(functionsDir)
  .filter((name) => existsSync(join(functionsDir, name, 'index.js')))
  .sort();

if (!names.length) {
  console.error('No edge functions found under supabase/functions/');
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });

for (const name of names) {
  const entry = join(functionsDir, name, 'index.js');
  const outfile = join(outDir, `${name}.js`);
  const banner =
    `// ${name} — GENERATED self-contained bundle for single-file (Dashboard) deploys.\n` +
    `// Source of truth: supabase/functions/${name}/index.js + supabase/functions/_shared/.\n` +
    `// Do not edit this file directly — regenerate with: npm run bundle`;
  try {
    execFileSync(
      'npx',
      [
        ...ESBUILD_ARGS,
        entry,
        '--bundle',
        '--format=esm',
        '--platform=neutral',
        '--external:npm:*',
        `--banner:js=${banner}`,
        `--outfile=${outfile}`,
      ],
      { stdio: ['ignore', 'pipe', 'inherit'], cwd: root },
    );
  } catch (error) {
    console.error(`FAIL bundling ${name}`);
    process.exit(1);
  }
  const kb = (statSync(outfile).size / 1024).toFixed(1);
  console.log(`bundled ${name} -> dist/functions/${name}.js (${kb} kB)`);
}
console.log(`${names.length} functions bundled.`);
